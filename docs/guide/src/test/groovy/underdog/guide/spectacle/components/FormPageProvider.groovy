                    }
                }
                row {
                    col("${CSS_3_COLS_RESPONSIVE} d-flex justify-content-between") {
                        // --8<-- [start:button]
                        button(
                            name: app.field.button,    // string
                            text: 'Execute',           // string
                            className: '+btn-danger'   // string
                        )
                        // --8<-- [end:button]
                        // --8<-- [start:resetLink]
                        resetLink(
                            name: app.field.reset,     // string
                            text: 'Reset form',        // string
                            className: '+link-success' // string
                        )
                        // --8<-- [end:resetLink]
                    }
                }
                onSubmit([],[]) { Context ctx ->
                    println("Form sent!")
                }
            }
        }
    }
}
